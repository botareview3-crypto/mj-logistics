/**
 * Every navigable subsystem has products, including the sections not yet
 * supplied by a distributor feed. These clearly labelled catalogue entries
 * keep navigation, filtering, product pages and cart flows usable; replace
 * them with supplier records when the production inventory is imported.
 */
function buildCoverageParts(): Part[] {
  const existingSubsystems = new Set(SEEDED_PARTS.map(part => part.subsystemId));
  const fallbackBrands = ['Bosch', 'Febi Bilstein', 'Valeo', 'MANN-FILTER'];

  return CATEGORY_ROOTS.flatMap(root => root.systems.flatMap(system => system.subsystems.flatMap((subsystem, index) => {
    if (existingSubsystems.has(subsystem.id)) return [];
    const basePrice = 18 + ((index * 11 + system.name.length) % 46);
    const accent = root.id === 'accessories' ? '#b7791f' : '#0077c7';
    return [0, 1].map(variant => ({
      id: `catalogue-${subsystem.id}-${variant + 1}`,
      sku: `MJ-${subsystem.id.slice(0, 8).toUpperCase()}-${variant + 1}`,
      name: `${subsystem.name} ${variant === 0 ? 'Replacement Part' : 'Service Kit'}`,
      brand: fallbackBrands[(index + variant) % fallbackBrands.length],
      systemId: system.id,
      subsystemId: subsystem.id,
      category: subsystem.name,
      partType: variant === 0 ? 'Replacement Part' : 'Service Kit',
      position: 'Universal',
      price: Number((basePrice + variant * 14.5).toFixed(2)),
      inStock: true,
      stockCount: 12 + index + variant * 7,
      deliveryDays: variant + 1,
      warrantyYears: 1,
      rating: 4.5,
      reviewCount: 0,
      images: [catalogueImage(subsystem.name, accent)],
      specs: { Category: subsystem.name, Application: 'Vehicle compatibility should be checked before ordering' },
      oemNumbers: [],
      description: `Catalogue item for ${subsystem.name}. Confirm vehicle compatibility before adding this part to your order.`,
      fitsVehicles: universalFitment,
      compatibleEngineIds: [],
    }));
  })));
}

